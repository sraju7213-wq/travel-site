/**
 * Fisher-Yates non-repeating shuffle.
 * Guarantees every video in the catalog is visited once before any repeat.
 * If previousLastId is provided, guarantees that the first video of the new cycle
 * never matches the last video of the prior cycle (zero consecutive duplicates).
 */
export function generateShuffledPlaylist(
  videos: HeroVideo[] = HERO_VIDEOS,
  previousLastId?: string
): HeroVideo[] {
  const arr = [...videos];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }

  // Prevent back-to-back duplicate across cycle boundaries
  if (previousLastId && arr.length > 1 && arr[0].id === previousLastId) {
    const swapIdx = 1 + Math.floor(Math.random() * (arr.length - 1));
    [arr[0], arr[swapIdx]] = [arr[swapIdx], arr[0]];
  }

  return arr;
}
