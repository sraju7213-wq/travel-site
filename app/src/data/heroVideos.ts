/**
 * Categorize a video into its primary destination group
 * so the shuffler can prevent back-to-back repetitions of the same place.
 */
export function getDestinationGroup(video: HeroVideo): string {
  const r = (video.region + " " + video.location).toLowerCase();
  if (r.includes("delhi")) return "delhi";
  if (r.includes("kashmir") || r.includes("srinagar") || r.includes("gulmarg")) return "kashmir";
  if (r.includes("ladakh") || r.includes("zanskar")) return "ladakh";
  if (r.includes("agra") || r.includes("taj mahal")) return "agra";
  if (r.includes("rajasthan") || r.includes("jaipur") || r.includes("jodhpur") || r.includes("jaisalmer")) return "rajasthan";
  if (r.includes("kerala") || r.includes("alleppey")) return "kerala";
  if (r.includes("varanasi") || r.includes("ganges")) return "varanasi";
  if (r.includes("nepal") || r.includes("kathmandu")) return "nepal";
  if (r.includes("goa")) return "goa";
  return "himalaya";
}

/**
 * Diverse-region shuffle algorithm.
 * Guarantees every video in the catalog is visited once before any repeat.
 * Crucially enforces that NO TWO CONSECUTIVE VIDEOS share the same destination/place,
 * creating an engaging, geographically varied journey across India & Nepal.
 * Also guarantees that across cycle boundaries, the first video never matches
 * the destination of the last video from the previous cycle.
 */
export function generateShuffledPlaylist(
  videos: HeroVideo[] = HERO_VIDEOS,
  previousLastId?: string
): HeroVideo[] {
  if (videos.length <= 1) return [...videos];

  const pool = [...videos];
  // Initial random permutation of pool
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  const result: HeroVideo[] = [];
  const prevVideo = previousLastId ? videos.find((v) => v.id === previousLastId) : undefined;
  let lastGroup = prevVideo ? getDestinationGroup(prevVideo) : undefined;
  let lastId = previousLastId;

  while (pool.length > 0) {
    // Select candidates that have a DIFFERENT destination group and different ID
    const candidates = pool.filter(
      (v) => getDestinationGroup(v) !== lastGroup && v.id !== lastId
    );

    const selectionPool =
      candidates.length > 0
        ? candidates
        : pool.filter((v) => v.id !== lastId);

    const chosenList = selectionPool.length > 0 ? selectionPool : pool;

    // Weight selection toward groups with the highest remaining count to avoid grouping at the tail
    const groupCounts = new Map<string, number>();
    for (const v of chosenList) {
      const g = getDestinationGroup(v);
      groupCounts.set(g, (groupCounts.get(g) || 0) + 1);
    }

    chosenList.sort((a, b) => {
      const countA = groupCounts.get(getDestinationGroup(a)) || 0;
      const countB = groupCounts.get(getDestinationGroup(b)) || 0;
      return countB - countA + (Math.random() - 0.5);
    });

    const chosen = chosenList[0];
    result.push(chosen);

    const removeIdx = pool.indexOf(chosen);
    if (removeIdx !== -1) {
      pool.splice(removeIdx, 1);
    }

    lastGroup = getDestinationGroup(chosen);
    lastId = chosen.id;
  }

  return result;
}
